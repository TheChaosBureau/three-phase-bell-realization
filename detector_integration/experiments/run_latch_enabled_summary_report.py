def _two_branch_summary_metrics(rows: list[dict[str, Any]]) -> dict[str, float]:
    winner_errors = np.asarray([float(row["winner_law_error"]) for row in rows], dtype=float)
    max_abs = np.asarray([float(row["max_abs_error"]) for row in rows], dtype=float)
    return {
        "rms_winner_law_error": float(np.sqrt(np.mean(winner_errors**2))),
        "max_winner_law_error": float(np.max(max_abs)),
    }


def _four_branch_summary_metrics(rows: list[dict[str, Any]]) -> dict[str, float]:
    rms_errors = np.asarray([float(row["rms_error"]) for row in rows], dtype=float)
    max_abs = np.asarray([float(row["max_abs_error"]) for row in rows], dtype=float)
    correlator_errors = np.asarray([float(row["correlator_error"]) for row in rows], dtype=float)
    return {
        "rms_weight_error": float(np.sqrt(np.mean(rms_errors**2))),
        "max_branch_frequency_error": float(np.max(max_abs)),
        "correlator_rms_error": float(np.sqrt(np.mean(correlator_errors**2))),
        "correlator_max_abs_error": float(np.max(correlator_errors)),
    }


def _mismatch_rows_at_levels(rows: list[dict[str, Any]], levels: tuple[float, ...]) -> list[dict[str, Any]]:
    return [
        {
            "kind": row["kind"],
            "level": row["level"],
            "two_branch_mean_rms_error": row["two_branch_mean_rms_error"],
            "two_branch_max_winner_law_error": row["two_branch_max_winner_law_error"],
            "four_branch_mean_rms_error": row["four_branch_mean_rms_error"],
            "four_branch_max_abs_error": row["four_branch_max_abs_error"],
            "max_correlator_error": row["max_correlator_error"],
            "chsh_abs_error": row["chsh_abs_error"],
        }
        for row in rows
        if float(row["level"]) in levels
    ]


def _write_summary_csv(path: Path, summary_metrics: dict[str, Any]) -> None:
    rows = [
        {"metric": "two_branch_rms_winner_law_error", "value": summary_metrics["two_branch_rms_winner_law_error"]},
        {"metric": "two_branch_max_winner_law_error", "value": summary_metrics["two_branch_max_winner_law_error"]},
        {"metric": "four_branch_rms_weight_error", "value": summary_metrics["four_branch_rms_weight_error"]},
        {"metric": "four_branch_max_branch_frequency_error", "value": summary_metrics["four_branch_max_branch_frequency_error"]},
        {"metric": "correlator_rms_error", "value": summary_metrics["correlator_rms_error"]},
        {"metric": "correlator_max_abs_error", "value": summary_metrics["correlator_max_abs_error"]},
        {"metric": "chsh_exact", "value": summary_metrics["chsh_exact"]},
        {"metric": "chsh_empirical", "value": summary_metrics["chsh_empirical"]},
        {"metric": "chsh_abs_error", "value": summary_metrics["chsh_abs_error"]},
    ]
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["metric", "value"])
        writer.writeheader()
        writer.writerows(rows)


def _write_spice_abstraction(
    path: Path,
    *,
    detector_spec: dict[str, Any],
    latch_config,
    envelope_params: dict[str, Any],
) -> None:
    path.write_text(
        "\n".join(
            [
                "# SPICE-Facing Detector + Latch Abstraction",
                "",
                "## Front-End Output",
                "",
                "For each branch `k`, the linear front-end exports an absorbed-power envelope `P_k(t) = Gamma(t) * w_k` where the normalized weights are generated by the exact front-end model and `Gamma(t)` is the shared envelope.",
                "",
                "## Detector Output",
                "",
                "Each branch detector is abstracted as a rare-event nucleation source whose first digital pulse time is sampled from the validated detector family under the applied envelope.",
                f"- Detector family: `{detector_spec['family']}`",
                f"- Detector params: `{json.dumps(detector_spec['model_params'], sort_keys=True)}`",
                f"- Envelope params: `{json.dumps(envelope_params, sort_keys=True)}`",
                "",
                "## Winner Latch Output",
                "",
                "The latch consumes branch pulse times and emits one exclusive winner plus a winner-valid flag.",
                f"- Input delay: {latch_config.input_delay_s:.3e} s",
                f"- Tie window: {latch_config.tie_window_s:.3e} s",
                f"- Settle time: {latch_config.settle_time_s:.3e} s",
                f"- Priority order: `{list(latch_config.priority_order)}`",
                "",
                "Semantics:",
                "",
                "- exactly one winner per trial if any branch fires,",
                "- arrivals inside the documented tie aperture resolve deterministically by priority order,",
                "- non-winning branches are suppressed after capture,",
                "- reset and re-arm are external trial-boundary operations for the later drain/closure block.",
                "",
                "## Future Drain / Closure Boundary",
                "",
                "The abstraction stops at `winner_index`, `winner_valid`, and loser suppression semantics. The physical post-click drain path is left for the next SPICE-facing closure ticket.",
                "",
            ]
        )
        + "\n",
        encoding="utf-8",
    )


def _write_markdown_report(
    path: Path,
    *,
    summary_metrics: dict[str, Any],
    detector_spec: dict[str, Any],
    latch_config,
    summary_source: str,
    mismatch_rows: list[dict[str, Any]],
    outputs: dict[str, Any],
    acceptance: dict[str, bool | str],
) -> None:
    top_row = detector_spec["search_summary_row"]
    decision = (
        "Proceed to SPICE-facing surrogate work."
        if acceptance["proceed_to_next_phase"]
        else "Hold SPICE work and debug the integration boundary."
    )
    lines = [
        "# Latch-Enabled Front-End Integration Summary",
        "",
        "## Metrics",
        "",
        f"- Two-branch RMS winner-law error: {summary_metrics['two_branch_rms_winner_law_error']:.6f}",
        f"- Two-branch max winner-law error: {summary_metrics['two_branch_max_winner_law_error']:.6f}",
        f"- Four-branch RMS weight error: {summary_metrics['four_branch_rms_weight_error']:.6f}",
        f"- Four-branch max branch-frequency error: {summary_metrics['four_branch_max_branch_frequency_error']:.6f}",
        f"- Correlator RMS error: {summary_metrics['correlator_rms_error']:.6f}",
        f"- Correlator max abs error: {summary_metrics['correlator_max_abs_error']:.6f}",
        f"- CHSH exact: {summary_metrics['chsh_exact']:.6f}",
        f"- CHSH empirical: {summary_metrics['chsh_empirical']:.6f}",
        f"- CHSH absolute error: {summary_metrics['chsh_abs_error']:.6f}",
        "",
        "## Mismatch Sensitivity",
        "",
        "| kind | level | two-branch RMS | two-branch max | four-branch RMS | four-branch max | max correlator error | CHSH abs error |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in mismatch_rows:
        lines.append(
            f"| {row['kind']} | {100.0 * float(row['level']):.0f}% | {float(row['two_branch_mean_rms_error']):.6f} | "
            f"{float(row['two_branch_max_winner_law_error']):.6f} | {float(row['four_branch_mean_rms_error']):.6f} | "
            f"{float(row['four_branch_max_abs_error']):.6f} | {float(row['max_correlator_error']):.6f} | {float(row['chsh_abs_error']):.6f} |"
        )
    lines.extend(
        [
            "",
            "## Latch Abstraction",
            "",
            f"- Input delay: {latch_config.input_delay_s:.3e} s",
            f"- Tie window: {latch_config.tie_window_s:.3e} s",
            f"- Settle time: {latch_config.settle_time_s:.3e} s",
            f"- Priority order: `{list(latch_config.priority_order)}`",
            "",
            "## Top Shot Trigger Parameter Set",
            "",
            f"- Source summary: `{summary_source}`",
            f"- Search score: {float(top_row['score']):.6f}",
            f"- Search race RMS error: {float(top_row['race_rms_error']):.6f}",
            f"- Search linearity RMS error: {float(top_row['linearity_rms_rel']):.6f}",
            f"- Search dark-count rate: {float(top_row['dark_count_rate']):.6f}",
            f"- Model params: `{json.dumps(detector_spec['model_params'], sort_keys=True)}`",
            "",
            "## Decision Gate",
            "",
            f"- Two-branch pass: {acceptance['two_branch_pass']}",
            f"- Four-branch pass: {acceptance['four_branch_pass']}",
            f"- Correlator pass: {acceptance['correlator_pass']}",
            f"- CHSH pass: {acceptance['chsh_pass']}",
            f"- Robustness pass: {acceptance['robustness_pass']}",
            f"- Decision: {decision}",
            f"- Next ticket: {acceptance['recommended_next_ticket']}",
            "",
            "## Artifacts",
            "",
            f"- Two-branch summary: `{outputs['two_branch_csv']}`",
            f"- Four-branch summary: `{outputs['four_branch_csv']}`",
            f"- Mismatch summary: `{outputs['mismatch_csv']}`",
            f"- SPICE abstraction: `{outputs['spice_abstraction_md']}`",
            f"- Two-branch plot: `{outputs['two_branch_plot']}`",
            f"- Four-branch weights plot: `{outputs['four_branch_weights_plot']}`",
            f"- Correlator plot: `{outputs['correlator_plot']}`",
            f"- CHSH plot: `{outputs['chsh_plot']}`",
            f"- Mismatch plot: `{outputs['mismatch_plot']}`",
        ]
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_latch_enabled_integration_report(
    outdir: str | Path,
    *,
    detector_next_summary_csv: str | Path = "artifacts/detector_next/results_summary.csv",
    n_two_branch_trials: int = 4_000,
    n_four_branch_trials: int = 6_000,
    n_mismatch_trials: int = 2_000,
    seed: int = 20260402,
) -> dict[str, Any]:
    output_dir = Path(outdir)
    output_dir.mkdir(parents=True, exist_ok=True)

    detector_spec = load_top_shot_trigger_spec(detector_next_summary_csv)
    detector_model_spec = {"family": detector_spec["family"], "model_params": dict(detector_spec["model_params"])}
    latch_config = validated_latch_arbiter_config(4)

    two_outputs = run_latch_enabled_two_branch_state_sweep(
        output_dir / "two_branch",
        detector_family="shot_trigger",
        detector_spec=detector_model_spec,
        envelope_params=dict(TWO_BRANCH_ENVELOPE),
        n_trials=n_two_branch_trials,
        seed=seed,
    )
    four_outputs = run_latch_enabled_four_branch_angle_sweep(
        output_dir / "four_branch",
        detector_family="shot_trigger",
        detector_spec=detector_model_spec,
        envelope_params=dict(FOUR_BRANCH_ENVELOPE),
        n_trials=n_four_branch_trials,
        seed=seed + 10_000,
    )
    mismatch_outputs = run_latch_enabled_mismatch_sweep(
        output_dir / "mismatch",
        detector_family="shot_trigger",
        detector_spec=detector_model_spec,
        envelope_params=dict(FOUR_BRANCH_ENVELOPE),
        n_trials=n_mismatch_trials,
        seed=seed + 20_000,
    )

    two_metrics = _two_branch_summary_metrics(two_outputs["rows"])
    four_metrics = _four_branch_summary_metrics(four_outputs["rows"])
    summary_metrics = {
        "two_branch_rms_winner_law_error": two_metrics["rms_winner_law_error"],
        "two_branch_max_winner_law_error": two_metrics["max_winner_law_error"],
        "four_branch_rms_weight_error": four_metrics["rms_weight_error"],
        "four_branch_max_branch_frequency_error": four_metrics["max_branch_frequency_error"],
        "correlator_rms_error": four_metrics["correlator_rms_error"],
        "correlator_max_abs_error": four_metrics["correlator_max_abs_error"],
        "chsh_exact": float(four_outputs["chsh"]["exact_s"]),
        "chsh_empirical": float(four_outputs["chsh"]["empirical_s"]),
        "chsh_abs_error": float(four_outputs["chsh"]["abs_error"]),
    }
    mismatch_rows = _mismatch_rows_at_levels(mismatch_outputs["rows"], levels=(0.02, 0.05))

    acceptance = {
        "two_branch_pass": summary_metrics["two_branch_rms_winner_law_error"] < 0.02
        and summary_metrics["two_branch_max_winner_law_error"] < 0.05,
        "four_branch_pass": summary_metrics["four_branch_rms_weight_error"] < 0.03
        and summary_metrics["four_branch_max_branch_frequency_error"] < 0.05,
        "correlator_pass": summary_metrics["correlator_rms_error"] < 0.05,
        "chsh_pass": abs(abs(summary_metrics["chsh_empirical"]) - 2.0 * math.sqrt(2.0)) < 0.1,
        "robustness_pass": all(
            float(row["two_branch_max_winner_law_error"]) < 0.05
            and float(row["four_branch_max_abs_error"]) < 0.05
            and float(row["max_correlator_error"]) < 0.05
            and float(row["chsh_abs_error"]) < 0.1
            for row in mismatch_rows
            if float(row["level"]) <= 0.02
        ),
    }
    acceptance["proceed_to_next_phase"] = all(
        [
            acceptance["two_branch_pass"],
            acceptance["four_branch_pass"],
            acceptance["correlator_pass"],
            acceptance["chsh_pass"],
            acceptance["robustness_pass"],
        ]
    )
    acceptance["recommended_next_ticket"] = (
        "Build the first SPICE-facing surrogate of the linear front-end plus detector pulse abstraction, then begin physical closure and drain integration."
        if acceptance["proceed_to_next_phase"]
        else "Debug the detector and latch integration boundary before any SPICE-facing work."
    )

    summary_csv = output_dir / "summary_metrics.csv"
    _write_summary_csv(summary_csv, summary_metrics)

    spice_abstraction_md = output_dir / "spice_abstraction.md"
    _write_spice_abstraction(
        spice_abstraction_md,
        detector_spec=detector_model_spec,
        latch_config=latch_config,
        envelope_params=dict(FOUR_BRANCH_ENVELOPE),
    )

    summary_json = output_dir / "summary_report.json"
    summary_json.write_text(
        json.dumps(
            {
                "summary_metrics": summary_metrics,
                "mismatch_rows": mismatch_rows,
                "top_shot_trigger": detector_spec,
                "latch_config": {
                    "input_delay_s": latch_config.input_delay_s,
                    "settle_time_s": latch_config.settle_time_s,
                    "tie_window_s": latch_config.tie_window_s,
                    "priority_order": list(latch_config.priority_order),
                },
                "two_branch": {"csv": two_outputs["csv"], "json": two_outputs["json"], "plot": two_outputs["plot"]},
                "four_branch": {
                    "csv": four_outputs["csv"],
                    "json": four_outputs["json"],
                    "weights_plot": four_outputs["weights_plot"],
                    "correlator_plot": four_outputs["correlator_plot"],
                    "chsh_plot": four_outputs["chsh_plot"],
                },
                "mismatch": {
                    "csv": mismatch_outputs["csv"],
                    "json": mismatch_outputs["json"],
                    "plot": mismatch_outputs["plot"],
                },
                "spice_abstraction_md": str(spice_abstraction_md),
                "acceptance": acceptance,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )

    summary_md = output_dir / "summary_report.md"
    _write_markdown_report(
        summary_md,
        summary_metrics=summary_metrics,
        detector_spec=detector_spec,
        latch_config=latch_config,
        summary_source=str(detector_next_summary_csv),
        mismatch_rows=mismatch_rows,
        outputs={
            "two_branch_csv": two_outputs["csv"],
            "four_branch_csv": four_outputs["csv"],
            "mismatch_csv": mismatch_outputs["csv"],
            "spice_abstraction_md": str(spice_abstraction_md),
            "two_branch_plot": two_outputs["plot"],
            "four_branch_weights_plot": four_outputs["weights_plot"],
            "correlator_plot": four_outputs["correlator_plot"],
            "chsh_plot": four_outputs["chsh_plot"],
            "mismatch_plot": mismatch_outputs["plot"],
        },
        acceptance=acceptance,
    )

    return {
        "summary_md": str(summary_md),
        "summary_json": str(summary_json),
        "summary_csv": str(summary_csv),
        "two_branch_csv": two_outputs["csv"],
        "four_branch_csv": four_outputs["csv"],
        "mismatch_csv": mismatch_outputs["csv"],
        "spice_abstraction_md": str(spice_abstraction_md),
        "top_shot_trigger_params": detector_spec["model_params"],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the latch-enabled front-end integration summary report.")
    parser.add_argument("--outdir", default="artifacts/front_end_integration")
    parser.add_argument("--detector-next-summary", default="artifacts/detector_next/results_summary.csv")
    parser.add_argument("--two-branch-trials", type=int, default=4_000)
    parser.add_argument("--four-branch-trials", type=int, default=6_000)
    parser.add_argument("--mismatch-trials", type=int, default=2_000)
    args = parser.parse_args()

    build_latch_enabled_integration_report(
        args.outdir,
        detector_next_summary_csv=args.detector_next_summary,
        n_two_branch_trials=args.two_branch_trials,
        n_four_branch_trials=args.four_branch_trials,
        n_mismatch_trials=args.mismatch_trials,
    )


if __name__ == "__main__":
    main()
